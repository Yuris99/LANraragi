"""Build the bundled labels from a pinned public-domain Korean dictionary.

Run with a directory containing the four original JSON files and LICENSE.
No network access or private catalog is used by this builder.
"""
import hashlib
import json
from pathlib import Path
import re
import sys

REVISION = '51233c8df9fd5d2247a82865ebef29cad8664b26'
SOURCES = {
    'result-korean-tag.json': 'e4744111783729d9403e92313a2db5ecfc61ac9e',
    'result-korean-series.json': '948b4daaf18d07105dd1429acbc90aa528d6af26',
    'result-korean-character.json': '52fc207c925c5146630ae3294dc34d54c1aac6bb',
    'result-korean-merge.json': 'd03788b763059c6e1b23c80f3ee0c89fd30692bc',
    'LICENSE': 'fdddb29aa445bf3d6a5d843d6dd77e10a9f99657',
}


def build(directory):
    originals = {}
    for filename, expected in SOURCES.items():
        raw = (directory / filename).read_bytes()
        actual = hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest()
        if actual != expected:
            raise ValueError('Upstream blob hash mismatch: ' + filename)
        originals[filename] = raw.decode('utf-8')
    labels = {}
    for filename in list(SOURCES)[:-1]:
        for key, value in json.loads(originals[filename]).items():
            if not isinstance(value, str) or not re.search('[가-힣]', value):
                continue
            if filename == 'result-korean-series.json':
                key = 'parody:' + key
            elif filename == 'result-korean-character.json':
                key = 'character:' + key
            key = re.sub(r'^tag:', '', key.lower())
            key = re.sub(r'^series:', 'parody:', key)
            value = re.sub(r'^(?:(?:female|male|mixed|tag|series|character):)+', '', value)
            # Keep namespace identities; a character name must not label an artist.
            existing = labels.setdefault(key, [])
            for alias in value.split('|'):
                alias = alias.strip()
                if alias and alias not in existing:
                    existing.append(alias)
    labels = {key: '|'.join(values) for key, values in sorted(labels.items())}
    header = ('"""Bundled Korean labels; generated by tools/build_tag_dictionary.py.\n'
              'Source: https://github.com/project-violet/tag-info/tree/' + REVISION + '\n\n'
              + originals['LICENSE'] + '"""\n\n')
    return header + 'LABELS = ' + json.dumps(labels, ensure_ascii=False, indent=2) + '\n'


if __name__ == '__main__':
    target = Path(__file__).resolve().parents[1] / 'tag_dictionary_data.py'
    target.write_text(build(Path(sys.argv[1])), encoding='utf-8', newline='\n')
