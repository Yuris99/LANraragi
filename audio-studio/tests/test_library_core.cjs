const assert=require('node:assert/strict');
const core=require('../web/library-core.js');
const edition=(id,media,translation,subtitles=[],resume=0)=>({id,work_id:'w',kind:'audio',title:id,credits:{},profile:{media_type:media,translation},tracks:[{id:'t'+id,resume,duration:60,subtitles}]});
const original=edition('original','audio','none'),translated=edition('translated','audio','subtitles',[{id:'sub'}],12),video=edition('video','video','embedded');
const work={id:'w',title:'달빛 편지',created:2,codes:[{provider:'dlsite',code:'RJ00000000'}],editions:[original,translated,video]};
assert.equal(core.preferred(work).id,'translated');
assert.equal(core.preferred(work,'video').id,'video');
assert.equal(core.preferred(work,'all','original').id,'original');
assert.equal(core.preferred(work,'resume').id,'translated');
assert.equal(core.resumeTrack(translated).resume,12);
assert.equal(core.resumeTrack({...translated,tracks:[{resume:60,duration:60}]}),null);
assert.equal(core.editionLabel(original),'원본 음성');
assert.equal(core.editionLabel(translated),'번역 자막');
assert.equal(core.editionLabel(video),'자막 영상');
assert.equal(core.editionLabel(edition('original-caption','audio','none',[{language:'ja'}])),'원본 음성','Original-language captions do not imply a translation');
assert.equal(core.filterWorks([work],'RJ00000000','video').length,1);
assert.equal(core.filterWorks([work],'not present').length,0);
assert.equal(core.filterWorks([{...work,editions:[original]}],'','resume').length,0);
assert.equal(core.filterWorks([{...work,editions:[original]}],'','subtitles').length,0);
assert.equal(core.time(63),'1:03');
assert.equal(core.time(Infinity),'—');
assert.equal(core.creator({...work,editions:[{credits:{circle:'테스트 서클'}}]}),'테스트 서클');
console.log('Library selection, explicit version labels, resume filtering, search and duration checks passed.');
